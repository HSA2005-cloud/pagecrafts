// The template library, as the discovery mockups draw it: a hundred and fourteen designs
// across nine batches (1-12, 13-24, 25-36, 37-51, 52-68, 69-83, 84-92, 93-104, 105-114), each led by a real photograph rather than the code-drawn
// motif (the motif stays as the fallback for a design that ships no image — see
// blueprint.ts). One blueprint per design; the generator
// still emits the markup, stylesheet and content schema together, so there is zero
// per-template UI and the gallery tile is parsed from the very files it advertises.
//
// Pricing follows the look: light / white (casual) tiles are Free; dark tiles are Pro
// (premium) or Premium (signature). buildTemplate enforces that from the palette.
//
// Photographs are hosted on Unsplash (Unsplash licence — free to use, no attribution
// required) and sit in the hero.image slot, which is an editable content field: a site
// owner swaps in their own photo without touching the template.

const PHOTO = "?w=1600&q=70&auto=format&fit=crop";
const img = (id: string): string => `https://images.unsplash.com/${id}${PHOTO}`;

const LIGHT = { bg: "#ffffff", ink: "#171717", muted: "#6b7280", panel: "#f4f4f5", rule: "#e5e7eb" };
const DARK = { bg: "#0b0b0f", ink: "#fafafa", muted: "#a1a1aa", panel: "#18181b", rule: "#27272a" };
const light = (accent: string): Palette => ({ ...LIGHT, accent });
const dark = (accent: string): Palette => ({ ...DARK, accent });

// Where a design came from (C-06). Every design in this file is first-party: the blueprint
// below it is the original, and buildTemplate generates the markup, stylesheet and content
// schema from it. There is no upstream project to credit.
//
// This used to point at github.com/pagecraft/templates, which has never existed — all 115
// designs recorded a provenance URL that answers 404. Nothing was stolen; the field was
// simply describing an origin that was never real, which is the failure C-06 is written to
// prevent and exactly what the licence audit is for (R2 D16).
//
// It now points at the file the design is actually defined in, which resolves and which a
// reader can check. A design sourced from somebody else's project must override this with
// their repository instead — see data/templates/sources/ and the normaliser, which refuses
// a source that names neither.
